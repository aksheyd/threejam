const BLANK = '..... ..... ..... ..... ..... ..... .....'

// A line of text as pixel art, 7 rows tall with a blank column between letters, so n letters are 6n - 1 wide.
export function textArt(text: string): string[] {
  const glyphs = [...text.toUpperCase()].map((c) => (GLYPHS[c] ?? BLANK).split(' '))
  return Array.from({ length: 7 }, (_, row) => glyphs.map((glyph) => glyph[row]).join('.'))
}
